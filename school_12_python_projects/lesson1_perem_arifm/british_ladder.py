# "Британская лестница": считаем, на сколько секунд продлится жизнь,
# если подниматься пешком на свой этаж вместо лифта.

# --- Переменные ---
steps_in_part = 0  # Ступеньки в одном пролёте
floor = 0  # Этаж, на котором живёт пользователь
total_seconds = 0  # Итоговое число секунд

# --- Константы ---
PARTS_IN_FLOOR = 2  # Пролётов лестницы на один этаж
SEC_LIVE_IN_STEP = 10  # Условные секунды жизни за ступеньку по условию задачи

print("\n=============\n")  # Разделитель

# Описание программы
print(
    "Данная программа считает на сколько секунд увеличится ваша жизнь при поднятии пешком на этаж на котором вы живёте"
)
print()  # Пустая строка

# input() даёт строку, int() превращает её в число
steps_in_part = int(input("Введите количество ступенек в пролёте: "))
floor = int(input("Введите этаж на котором вы живёте: "))

# Расчёт: всего ступенек × секунд за ступеньку
# Число пролётов получаем как PARTS_IN_FLOOR * floor: формула предполагает
# подъём на floor полных этажей от начального уровня.
total_seconds = steps_in_part * PARTS_IN_FLOOR * floor * SEC_LIVE_IN_STEP

print()  # Пустая строка

# f-строка подставляет значения переменных вместо {floor} и {total_seconds}
print(f"Ваша жизнь при поднятии на {floor} этаж увеличилась на {total_seconds} секунд")

print("\n=============\n")
